//! Canonical JSON text and small value helpers shared by the validators.
//!
//! Depends on: `serde_json`. Called by: confirm (token binding), validators.
//! Invariant: two values that differ only in object key order produce the same canonical text.

use serde_json::Value;

/// Serializes `value` with object keys sorted at every level, so it can be compared as text.
#[must_use]
pub(crate) fn canonical(value: &Value) -> String {
    let mut out = String::new();
    write(value, &mut out);
    out
}

fn write(value: &Value, out: &mut String) {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            out.push('{');
            for (i, key) in keys.into_iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                out.push_str(&Value::String(key.clone()).to_string());
                out.push(':');
                if let Some(v) = map.get(key) {
                    write(v, out);
                }
            }
            out.push('}');
        }
        Value::Array(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write(item, out);
            }
            out.push(']');
        }
        other => out.push_str(&other.to_string()),
    }
}

/// True when `text` is non-empty, at most `max` characters and has no control characters.
#[must_use]
pub(crate) fn is_clean_text(text: &str, max: usize) -> bool {
    !text.is_empty() && text.chars().count() <= max && !text.chars().any(char::is_control)
}
