//! Writes or checks the core API's TypeScript bindings in `ui/src/protocol/core/` (`index.ts`,
//! `status.ts`, `terminal.ts`, `keys.ts`, `instructions.ts`, `changes.ts`, `documents.ts`, `speech.ts`,
//! `preview.ts`, `connectors.ts`, `projects.ts`, `vibe.ts`).
//!
//! Usage (from anywhere in the repo): `cargo run -p vw-core-api --features ts --bin gen-core-ts --
//! --write` regenerates; `-- --check` exits 1 when a committed file differs (CI drift check,
//! `scripts/public/check.sh`).
//! Depends on: `vw_core_api::ts`. Called by: developers, check.sh.

use std::path::PathBuf;
use std::process::ExitCode;

const HEADER: &str = "\
/*
 * GENERATED by crates/vw-core-api (bin gen-core-ts, ts-rs) from the Rust core API types.
 * Do not edit: change the Rust types and run
 *   cargo run -p vw-core-api --features ts --bin gen-core-ts -- --write
 * scripts/public/check.sh fails when this file and the Rust types disagree.
 */
";

fn folder() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/protocol/core")
}

fn write(path: &PathBuf, text: &str) -> bool {
    let written = path
        .parent()
        .map_or(Ok(()), std::fs::create_dir_all)
        .and_then(|()| std::fs::write(path, text));
    match written {
        Ok(()) => {
            println!("wrote {}", path.display());
            true
        }
        Err(error) => {
            eprintln!("cannot write {}: {error}", path.display());
            false
        }
    }
}

fn current(path: &PathBuf, text: &str) -> bool {
    match std::fs::read_to_string(path) {
        Ok(found) if found == text => true,
        Ok(_) => {
            eprintln!(
                "{} is stale: run `cargo run -p vw-core-api --features ts --bin gen-core-ts -- --write`",
                path.display()
            );
            false
        }
        Err(error) => {
            eprintln!("cannot read {}: {error}", path.display());
            false
        }
    }
}

fn main() -> ExitCode {
    let mode = std::env::args().nth(1).unwrap_or_default();
    let modules = vw_core_api::ts::typescript_modules(HEADER);
    let ok = match mode.as_str() {
        "--write" => {
            modules
                .iter()
                // Every file is attempted (no short-circuit), then the result is combined.
                .map(|(name, text)| write(&folder().join(name), text))
                .filter(|ok| !ok)
                .count()
                == 0
        }
        "--check" => {
            let fresh = modules
                .iter()
                .map(|(name, text)| current(&folder().join(name), text))
                .filter(|ok| !ok)
                .count()
                == 0;
            if fresh {
                println!("core TypeScript bindings are current");
            }
            fresh
        }
        _ => {
            eprintln!("usage: gen-core-ts --write | --check");
            false
        }
    };
    if ok {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    }
}
