"""Copy the independent action fixture and app overrides from a read-only helper catalog.

Called by maintainers with --catalog PATH --write or --check; no helper build or execution.
"""
import argparse
import copy
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3] / "crates/vw-core-api/src/chrome_control"
GATED = ("clipboard.read", "clipboard.write", "network.intercept", "tabs.emulate", "files.wait_download")
DESCRIPTIONS = {
    "page.read": "Controls + preview. interactiveOnly:false: text/structure; options:true: options; ref: subtree; summary:true: DOM counts/coverage. maxChars: first preview. Continue with returned args; reassemble JSON details.",
    "page.find": "Find by label, role, text or placeholder with deterministic ranking (five matches by default). summary:true returns captured match counts and coverage without refs; scope:viewport limits matching to the viewport. Tied matches are ambiguous; inspect them before choosing a ref. Continue with the returned cursor for remaining candidates.",
    "page.click": "Click an observed element in the active tab; POST needs sending permission. Partial observation does not mean input failed: inspect the receipt before retrying.",
    "page.type": "Type into an observed editable element, excluding passwords, and return its live state plus bounded observations. Input needs the tab active in its window. Partial observation does not mean input failed: inspect the result before retrying.",
    "page.select": "Choose a native select option and return its live value plus bounded observations. Supply exactly one of value (exact option value) or text (visible label). Input needs the tab active in its window; inspect partial observation before retrying input.",
}


def outputs(catalog):
    """The fixture is verbatim data; only the app's descriptions and effective find default differ."""
    rows = {row["id"]: row for row in catalog["actions"]}
    overrides = []
    for action in (*GATED, *DESCRIPTIONS):
        row = copy.deepcopy(rows[action])
        if action in DESCRIPTIONS:
            row["description"] = DESCRIPTIONS[action]
            # The action lookup is itself budgeted. Keep validation constraints verbatim; explain
            # optional fields once in the short action description instead of repeating long prose.
            for name, prop in row["inputSchema"]["properties"].items():
                prop.pop("description", None)
                if name == "scope":
                    prop["description"] = "Viewport; omit for document. Needs viewport support."
                elif name == "observation":
                    prop["description"] = "Changes or full reset; requires observation support."
                elif name == "query":
                    prop["description"] = "Required for a new search; omit with cursor."
        if action == "page.find":
            row["inputSchema"]["properties"]["limit"]["default"] = 5
        overrides.append(row)
    fixture = "{\n" + ",\n".join(
        f"  {json.dumps(key)}: " + (
            "[\n" + ",\n".join("    " + json.dumps(row, ensure_ascii=False) for row in value) + "\n  ]"
            if key == "actions" else json.dumps(value, ensure_ascii=False)
        ) for key, value in catalog.items()
    ) + "\n}\n"
    app = {"description": "App action descriptions and schemas; generated by tools/public/codegen/chrome_actions.py. Applied only to arguments advertised by the running helper.", "actions": overrides}
    return {ROOT / "fixtures/catalog.json": fixture,
            ROOT / "action_catalog.json": json.dumps(app, ensure_ascii=False, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs(json.loads(args.catalog.read_text(encoding="utf-8"))).items():
        if args.write:
            path.write_text(content, encoding="utf-8", newline="\n")
        elif path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Chrome actions differ: regenerate {path.name} with --write")
    print("Chrome action fixture and overrides match the helper catalog")


if __name__ == "__main__":
    main()
