"""Emit Rust (serde) source for the schema, one file per area, plus the module index.

Role: turns ir.py definitions into `crates/vw-protocol/src/generated/*.rs`. Optional-versus-null
mapping (the heart of the exactness guarantee):
  required, not null  -> `T`
  required, nullable  -> `Option<T>` (must be present, `null` allowed, always serialised)
  optional, not null  -> `Option<T>` skipped when None (absent means "server default"; a
                         present `null` is rejected, as Pydantic rejects it)
  optional, nullable  -> `Maybe<T>` (absent / null / value stay distinct)
String enums and tagged unions expand through the macros in support.rs and keep an `Unrecognized`
variant for forward compatibility. Depends on: ir.py, naming.py, areas.py. Called by: generate.py.
Output is plain text; generate.py formats it with rustfmt.
"""

from __future__ import annotations

import re

from areas import refs_of
from ir import (
    Def,
    EnumDef,
    Field,
    ListOf,
    Lit,
    MapOf,
    ModelDef,
    Nullable,
    Prim,
    Ref,
    Schema,
    TypeRef,
    UnionDef,
    UntaggedDef,
)
from naming import rust_field_ident, rust_variant_ident

HEADER = """\
//! {title}
//!
//! GENERATED by tools/public/codegen from Mistral Vibe {version} (Apache-2.0); DO NOT EDIT.
//! Regenerate with `python tools/public/codegen/generate.py --write`; CI fails on any drift.
//! Source models are cited per item. Property constraints (min/max length, ranges) are not
//! generated: Vibe validates them and answers with a protocol error.
#![allow(
    unused_imports,
    clippy::pedantic,
    clippy::large_enum_variant,
    clippy::struct_excessive_bools
)]

use super::*;
use serde::{{Deserialize, Serialize}};
use std::collections::BTreeMap;
"""

PRELUDE_NAMES = frozenset("Option Result Vec String Box Some None Ok Err Self Default Maybe".split())


def doc_lines(text: str, indent: str = "") -> list[str]:
    """Render text as `///` lines. Leading whitespace is dropped so rustdoc sees no code blocks."""
    out: list[str] = []
    for raw in text.replace("```", "").splitlines():
        line = raw.strip()
        out.append(f"{indent}/// {line}".rstrip() if line else f"{indent}///")
    return out


def rust_type(t: TypeRef, boxed: bool = False) -> str:
    """The Rust spelling of a type reference."""
    if isinstance(t, Prim):
        return {"string": "String", "int": "i64", "float": "f64", "bool": "bool", "json": "serde_json::Value"}[t.kind]
    if isinstance(t, Lit):
        return {bool: "bool", int: "i64", str: "String"}[type(t.value)]
    if isinstance(t, ListOf):
        return f"Vec<{rust_type(t.item)}>"
    if isinstance(t, MapOf):
        return f"BTreeMap<String, {rust_type(t.value)}>"
    if isinstance(t, Nullable):
        return f"Option<{rust_type(t.inner)}>"
    return f"Box<{t.name}>" if boxed else t.name


def field_semantics(f: Field) -> str:
    """One-phrase statement of the Pydantic contract, written into the field's doc comment."""
    if f.discriminator:
        return "union tag, always present"
    req = "required" if f.required else "optional (may be absent)"
    return f"{req}{', may be null' if f.nullable else ''}"


def emit_field(f: Field) -> list[str]:
    """Doc, serde attributes and declaration for one struct field."""
    inner = rust_type(f.type, f.boxed)
    is_json = isinstance(f.type, Prim) and f.type.kind == "json"
    attrs: list[str] = []
    if f.wire != f.py_name:
        attrs.append(f'#[serde(rename = "{f.wire}")]')
    if f.required and not f.nullable:
        decl = inner
    elif f.required:
        decl = f"Option<{inner}>"
        attrs.append('#[serde(deserialize_with = "nullable")]')
    elif f.nullable or is_json:
        decl = f"Maybe<{inner}>"
        attrs.append('#[serde(default, skip_serializing_if = "Maybe::is_absent")]')
    else:
        decl = f"Option<{inner}>"
        attrs.append('#[serde(default, skip_serializing_if = "Option::is_none", deserialize_with = "present")]')
    desc = f.doc.strip().replace("\n", " ") + " " if f.doc.strip() else ""
    lines = doc_lines(f"{desc}Wire key `{f.wire}`; {field_semantics(f)}.", "    ")
    lines += [f"    {a}" for a in attrs]
    lines.append(f"    pub {rust_field_ident(f.py_name)}: {decl},")
    return lines


def emit_model(d: ModelDef) -> list[str]:
    """A struct with serde derives; unknown incoming fields are ignored (forward compatible)."""
    lines = doc_lines(f"{d.doc}\n\nSource: `{d.source}`." if d.doc else f"Vibe model `{d.name}`.\n\nSource: `{d.source}`.")
    lines.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
    lines.append(f"pub struct {d.name} {{")
    for f in d.fields:
        lines += emit_field(f)
    lines.append("}")
    return lines


def _unique_variants(wires: list[str]) -> list[str]:
    seen: dict[str, int] = {}
    out = []
    for w in wires:
        base = rust_variant_ident(w)
        seen[base] = seen.get(base, 0) + 1
        out.append(base if seen[base] == 1 else f"{base}{seen[base]}")
    return out


def emit_enum(d: EnumDef) -> list[str]:
    """A string enum via `string_enum!`."""
    lines = ["string_enum! {"]
    lines += doc_lines(f"{d.doc}\n\nSource: `{d.source}`." if d.doc else f"Closed set of string values.\n\nSource: `{d.source}`.", "    ")
    lines.append(f"    {d.name} {{")
    for variant, wire in zip(_unique_variants(d.values), d.values, strict=True):
        lines += doc_lines(f"Wire value `{wire}`.", "        ")
        lines.append(f'        {variant} = "{wire}",')
    lines += ["    }", "}"]
    return lines


def emit_union(d: UnionDef) -> list[str]:
    """A discriminated union via `tagged_union!`."""
    lines = ["tagged_union! {"]
    lines += doc_lines(f"Discriminated union on `{d.tag}`. Unknown tags decode to `Unrecognized`.\n\nSource: `{d.source}`.", "    ")
    lines.append(f'    {d.name}, tag = "{d.tag}" {{')
    for variant, (wire, model) in zip(_unique_variants([w for w, _ in d.members]), d.members, strict=True):
        lines += doc_lines(f"`{d.tag} = \"{wire}\"`.", "        ")
        lines.append(f'        {variant}("{wire}") => {model},')
    lines += ["    }", "}"]
    return lines


def _untagged_variant(t: TypeRef, used: set[str]) -> str:
    base = {"string": "Text", "int": "Int", "float": "Float", "bool": "Bool", "json": "Json"}[t.kind] if isinstance(t, Prim) else (
        t.name if isinstance(t, Ref) else "List" if isinstance(t, ListOf) else "Map" if isinstance(t, MapOf) else "Other"
    )
    name, i = base, 2
    while name in used:
        name, i = f"{base}{i}", i + 1
    used.add(name)
    return name


def emit_untagged(d: UntaggedDef) -> list[str]:
    """A serde untagged enum; members are pre-ordered most-specific first (introspect.py)."""
    lines = doc_lines(f"Union without a discriminator; members are tried in order.\n\nSource: `{d.source}`.")
    lines += ["#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]", "#[serde(untagged)]", f"pub enum {d.name} {{"]
    used: set[str] = set()
    for m in d.members:
        lines += doc_lines(f"A `{rust_type(m)}` value.", "    ")
        lines.append(f"    {_untagged_variant(m, used)}({rust_type(m)}),")
    lines.append("}")
    return lines


def emit_def(d: Def) -> list[str]:
    """Dispatch on definition kind."""
    if isinstance(d, ModelDef):
        return emit_model(d)
    if isinstance(d, EnumDef):
        return emit_enum(d)
    if isinstance(d, UnionDef):
        return emit_union(d)
    return emit_untagged(d)


def emit_file(title: str, names: list[str], schema: Schema) -> str:
    """One generated module: header plus its definitions in name order."""
    out = HEADER.format(title=title, version=schema.vibe_version).splitlines()
    for name in names:
        out.append("")
        out += emit_def(schema.defs[name])
    return "\n".join(out) + "\n"


def check_names(schema: Schema) -> None:
    """Fail when a definition name would shadow something the generated code relies on."""
    clash = sorted(n for n in schema.defs if n in PRELUDE_NAMES)
    if clash:
        raise ValueError(f"definition names clash with Rust prelude/support names: {clash}")
    for d in schema.defs.values():
        for ref in refs_of(d):
            if ref not in schema.defs:
                raise ValueError(f"{d.name} refers to unknown definition {ref}")
    if not all(re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", n) for n in schema.defs):
        raise ValueError("definition names must be plain identifiers")


def emit_mod_index(stems: list[str], extra: list[str]) -> str:
    """`generated/mod.rs`: declares support (macros first), the area modules and re-exports all."""
    lines = [
        "//! Generated Vibe app-server protocol types, one module per protocol area.",
        "//!",
        "//! GENERATED by tools/public/codegen; DO NOT EDIT. Everything is re-exported flat from",
        "//! `vw_protocol`, so callers never name the area modules.",
        "#![allow(clippy::pedantic)]",
        "",
        "#[macro_use]",
        "mod support;",
        "pub use support::Maybe;",
        "pub(crate) use support::{nullable, present};",
        "",
    ]
    for stem in sorted(stems + extra):
        lines += [f"mod {stem};", f"pub use {stem}::*;"]
    return "\n".join(lines) + "\n"
