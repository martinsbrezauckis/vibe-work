def _ty(name: str | None) -> str:
    return name or "Untyped"


def emit_rust(schema: Schema) -> str:
    """`methods.rs` source: traits, marker types and method-name lists."""
    out = RUST_HEADER.format(version=schema.vibe_version).splitlines()
    out += ["", "/// Marker types for every client request method.", "pub mod request {", "    use super::*;", "    markers! {", "        RequestMethod;"]
    out += [f'        "{m}" => {method_type_name(m)}({_ty(p)}, {_ty(r)}),' for m, (p, r) in schema.requests.items()]
    out += ["    }", "}", "", "/// Marker types for every server-to-client request method.", "pub mod server_request {", "    use super::*;", "    markers! {", "        ServerRequestMethod;"]
    out += [f'        "{m}" => {method_type_name(m)}({_ty(p)}, {_ty(r)}),' for m, (p, r) in schema.server_requests.items()]
    out += ["    }", "}", "", "/// Marker types for every server notification.", "pub mod notification {", "    use super::*;", "    notification_markers! {"]
    out += [f'        "{m}" => {method_type_name(m)}({_ty(p)}),' for m, p in schema.notifications.items()]
    out += ["    }", "}"]
    for const, doc, names in (
        ("REQUEST_METHODS", "client request", schema.requests),
        ("NOTIFICATION_METHODS", "server notification", schema.notifications),
        ("SERVER_REQUEST_METHODS", "server request", schema.server_requests),
    ):
        out += ["", f"/// Every {doc} method name this version knows.", f"pub const {const}: &[&str] = &["]
        out += [f'    "{m}",' for m in names] + ["];"]
    return "\n".join(out) + "\n"


def emit_reencode(schema: Schema) -> str:
    """`reencode.rs` source."""
    out = REENCODE_HEADER.format(version=schema.vibe_version).splitlines()
    arms: list[tuple[str, str, str]] = []
    for m, (p, r) in schema.requests.items():
        arms += [("RequestParams", m, p or ""), ("RequestResult", m, r or "")]
    for m, p in schema.notifications.items():
        arms.append(("NotificationParams", m, p or ""))
    for m, (p, r) in schema.server_requests.items():
        arms += [("ServerRequestParams", m, p or ""), ("ServerRequestResult", m, r or "")]
    out += [f'        (Payload::{k}, "{m}") => through::<{ty}>(value),' for k, m, ty in arms if ty]
    out += ["        _ => None,", "    }", "}"]
    return "\n".join(out) + "\n"


def emit_ts(schema: Schema) -> str:
    """`methods.ts` source: three maps from method name to payload types."""
    from ts_emit import HEADER

    def side(name: str | None) -> str:
        return name or "JsonValue"

    used = {n for pair in list(schema.requests.values()) + list(schema.server_requests.values()) for n in pair if n}
    used |= {n for n in schema.notifications.values() if n}
    lines = HEADER.format(title="Method registry: method name to params/result types.", version=schema.vibe_version).splitlines()
    lines += ["", 'import type { JsonValue } from "./support";', 'import type {']
    lines += [f"  {n}," for n in sorted(used)] + ['} from "./index";', ""]
    lines += ["/** Client request methods: name to params and result. */", "export interface RequestMap {"]
    lines += [f'  "{m}": {{ params: {side(p)}; result: {side(r)} }};' for m, (p, r) in schema.requests.items()] + ["}", ""]
    lines += ["/** Server notifications: name to params. */", "export interface NotificationMap {"]
    lines += [f'  "{m}": {{ params: {side(p)} }};' for m, p in schema.notifications.items()] + ["}", ""]
    lines += ["/** Server-to-client requests: name to params and the result the client returns. */", "export interface ServerRequestMap {"]
    lines += [f'  "{m}": {{ params: {side(p)}; result: {side(r)} }};' for m, (p, r) in schema.server_requests.items()] + ["}", ""]
    lines += ["/** Every client request method name. */", "export type RequestMethod = keyof RequestMap;",
              "/** Every server notification method name. */", "export type NotificationMethod = keyof NotificationMap;",
              "/** Every server request method name. */", "export type ServerRequestMethod = keyof ServerRequestMap;"]
    return "\n".join(lines) + "\n"
