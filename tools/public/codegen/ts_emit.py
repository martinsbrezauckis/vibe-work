"""Emit TypeScript declarations for the schema, one file per area.

Role: turns ir.py definitions into `ui/src/protocol/generated/*.ts`. Optional-versus-null maps
one-to-one onto TypeScript (`exactOptionalPropertyTypes` is on in the UI project):
  required, not null -> `x: T`        required, nullable -> `x: T | null`
  optional, not null -> `x?: T`       optional, nullable -> `x?: T | null`
String enums are closed literal unions (the Rust side keeps an `Unknown` variant; the TS side is
types only, see support.ts). Discriminated unions get an `Unrecognized<tag>` member (see templates/support.ts).
Depends on: ir.py, areas.py. Called by: generate.py (which formats the output with prettier).
"""

from __future__ import annotations

import json
import re

from areas import refs_of
from ir import (
    Def,
    EnumDef,
    Field,
    ListOf,
    Lit,
    MapOf,
    ModelDef,
    Nullable,
    Prim,
    Schema,
    TypeRef,
    UnionDef,
    UntaggedDef,
)

HEADER = """\
/**
 * {title}
 *
 * GENERATED by tools/public/codegen from Mistral Vibe {version} (Apache-2.0); DO NOT EDIT.
 * Regenerate with `python tools/public/codegen/generate.py --write`; CI fails on any drift.
 * Source models are cited per item. Property constraints (min/max length, ranges) are not
 * generated: Vibe validates them and answers with a protocol error.
 */
"""

IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def ts_doc(text: str, indent: str = "") -> list[str]:
    """JSDoc block for `text` (the closing-comment sequence is neutralised)."""
    body = text.replace("*/", "* /").splitlines() or [""]
    if len(body) == 1:
        return [f"{indent}/** {body[0].strip()} */"]
    return [f"{indent}/**"] + [f"{indent} * {ln.strip()}".rstrip() for ln in body] + [f"{indent} */"]


def ts_type(t: TypeRef) -> str:
    """The TypeScript spelling of a type reference."""
    if isinstance(t, Prim):
        return {"string": "string", "int": "number", "float": "number", "bool": "boolean", "json": "JsonValue"}[t.kind]
    if isinstance(t, Lit):
        return json.dumps(t.value) if not isinstance(t.value, bool) else ("true" if t.value else "false")
    if isinstance(t, ListOf):
        inner = ts_type(t.item)
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if isinstance(t, MapOf):
        return f"Record<string, {ts_type(t.value)}>"
    if isinstance(t, Nullable):
        return f"{ts_type(t.inner)} | null"
    return t.name


def emit_field(f: Field) -> list[str]:
    """JSDoc plus declaration for one interface property."""
    key = f.wire if IDENT.match(f.wire) else json.dumps(f.wire)
    optional = "" if f.required else "?"
    base = ts_type(f.type)
    # JsonValue already includes null, so `| null` would be redundant.
    nullable = " | null" if f.nullable and base != "JsonValue" else ""
    semantics = "union tag, always present" if f.discriminator else (
        ("required" if f.required else "optional (may be absent)") + (", may be null" if f.nullable else "")
    )
    desc = f.doc.strip().replace("\n", " ") + " " if f.doc.strip() else ""
    return ts_doc(f"{desc}Wire key `{f.wire}`; {semantics}.", "  ") + [f"  {key}{optional}: {base}{nullable};"]


def emit_def(d: Def) -> list[str]:
    """Declarations for one definition."""
    if isinstance(d, ModelDef):
        doc = f"{d.doc}\n\nSource: `{d.source}`." if d.doc else f"Vibe model `{d.name}`.\n\nSource: `{d.source}`."
        lines = ts_doc(doc) + [f"export interface {d.name} {{"]
        for f in d.fields:
            lines += emit_field(f)
        return lines + ["}"]
    if isinstance(d, EnumDef):
        doc = f"{d.doc}\n\nSource: `{d.source}`." if d.doc else f"Closed set of string values.\n\nSource: `{d.source}`."
        return ts_doc(doc) + [f"export type {d.name} = " + " | ".join(json.dumps(v) for v in d.values) + ";"]
    if isinstance(d, UnionDef):
        members = " | ".join(sorted({m for _, m in d.members}))
        doc = f"Discriminated union on `{d.tag}`; `Unrecognized` covers tags newer than this version.\n\nSource: `{d.source}`."
        return ts_doc(doc) + [f'export type {d.name} = {members} | Unrecognized<"{d.tag}">;']
    members = " | ".join(ts_type(m) for m in d.members)
    return ts_doc(f"Union without a discriminator.\n\nSource: `{d.source}`.") + [f"export type {d.name} = {members};"]


def emit_file(stem: str, names: list[str], schema: Schema, file_of: dict[str, str]) -> str:
    """One generated TS file with the imports it needs from sibling files and support.ts."""
    out = HEADER.format(title=f"{stem} protocol types.", version=schema.vibe_version).splitlines()
    needs_support: set[str] = set()
    foreign: dict[str, set[str]] = {}
    for name in names:
        d = schema.defs[name]
        for ref in refs_of(d):
            if file_of[ref] != stem:
                foreign.setdefault(file_of[ref], set()).add(ref)
        if isinstance(d, UnionDef):
            needs_support.add("Unrecognized")
        body = "\n".join(emit_def(d))
        if "JsonValue" in body:
            needs_support.add("JsonValue")
    out.append("")
    if needs_support:
        out.append(f'import type {{ {", ".join(sorted(needs_support))} }} from "./support";')
    for other, refs in sorted(foreign.items()):
        out.append(f'import type {{ {", ".join(sorted(refs))} }} from "./{other}";')
    for name in names:
        out.append("")
        out += emit_def(schema.defs[name])
    return "\n".join(out) + "\n"


def emit_index(stems: list[str], extra: list[str]) -> str:
    """`index.ts`: re-exports every generated file so callers import from one place."""
    lines = HEADER.format(title="Barrel for the generated protocol types.", version="").splitlines()
    lines = [ln for ln in lines if "from Mistral Vibe" not in ln]
    lines.append("")
    lines.append('export type { JsonValue, Unrecognized } from "./support";')
    for stem in sorted(stems + extra):
        lines.append(f'export type * from "./{stem}";')
    return "\n".join(lines) + "\n"
