/**
 * Generates the public vocabulary reference and marked Debug API copy from the UI/Rust JSON.
 * Depends on Node's filesystem API; called by check.sh and contributors with --write or --check.
 * Invariant: documentation lists canonical words while retaining protocol IDs for automation.
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../", import.meta.url);
const source = JSON.parse(
  readFileSync(new URL("crates/vw-vocabulary/vocabulary.json", root), "utf8"),
);
const destination = new URL("docs/public/VOCABULARY.md", root);
const debugDestination = new URL("docs/public/DEBUG_API.md", root);
const debugSource = readFileSync(debugDestination, "utf8");
const browser = source.browserPermissions;
const kinds = source.vaultKinds;
const permissions = source.vaultPermissions;
const debugCopy = {
  fullAccess: source.accessModes["auto-approve"].name,
  browser: `\nThe window calls this choice **${browser.closeUserTabs.name}**.\nFor closing tabs you opened, **${browser.closeAsk.name}** asks **Close** or **Keep** each time; **${browser.closeAllow.name}** lets the agent close them during your task. These are \`closeUserTabs: false\` and \`true\` on the wire. App preview cannot be closed by the agent.\n`,
  vault: `\nThe window names them **${kinds.vibeWork.name}**, **${kinds.shellx.name}** and **${kinds.desktop.name}**. Its per-project entry\npermissions are **${permissions.askEachTime.name}**, **${permissions.allowed.name}** and **${permissions.never.name}** (\`askEachTime\`, \`allowed\`, \`never\` on the wire).\n**${source.locks.agentPause.name}** pauses agents' use of secrets while sessions keep working;\n**${source.locks.vaultLock.name}** protects the vault cryptographically and pauses model requests until unlock.\n`,
};
const found = new Set();
const debugDocument = debugSource.replace(
  /<!-- vocabulary:(\w+):start -->[\s\S]*?<!-- vocabulary:\1:end -->/g,
  (match, id) => {
    if (!Object.hasOwn(debugCopy, id))
      throw new Error(`Unknown vocabulary block: ${id}`);
    found.add(id);
    return `<!-- vocabulary:${id}:start -->${debugCopy[id]}<!-- vocabulary:${id}:end -->`;
  },
);
for (const id of Object.keys(debugCopy)) {
  if (!found.has(id))
    throw new Error(`Missing Debug API vocabulary block: ${id}`);
}
const sections = {
  accessModes: "Access modes",
  thinkingLevels: source.texts.thinkingLevel,
  vaultKinds: "Vault kinds",
  vaultPermissions: "Vault permissions",
  browserPermissions: "Browser delegation permissions",
  locks: "Agent access and vault lock",
};
const cell = (value) => value.replaceAll("|", "\\|").replaceAll("\n", " ");
const tables = Object.entries(sections).map(([group, heading]) => {
  const rows = Object.entries(source[group]).map(
    ([id, value]) =>
      `| \`${id}\` | ${cell(value.name)} | ${cell(value.description)} | ${cell(value.tooltip)} |`,
  );
  return `## ${heading}\n\n| ID | Name | Description | Tooltip |\n| --- | --- | --- | --- |\n${rows.join("\n")}`;
});
const document =
  [
    "<!-- GENERATED by tools/public/codegen/vocabulary.mjs from crates/vw-vocabulary/vocabulary.json. Do not edit. -->",
    "# Vocabulary",
    "These names are shared by the composer, Settings, setup, status bar and native core dialogs. IDs remain unchanged in commands and storage.",
    `Models use Vibe's reported display name, falling back to the configured alias. ${source.texts.defaultModel} applies to new chats. ${source.texts.defaultThinkingLevel} offers ${source.texts.modelDefaultThinking} plus only that model's reported levels. Custom models, levels and profiles retain their configured names.`,
    ...tables,
  ].join("\n\n") + "\n";

if (process.argv[2] === "--write") {
  writeFileSync(destination, document);
  writeFileSync(debugDestination, debugDocument);
  process.stdout.write("vocabulary reference and Debug API wording written\n");
} else if (process.argv[2] === "--check") {
  if (
    readFileSync(destination, "utf8") !== document ||
    debugSource !== debugDocument
  ) {
    process.stderr.write(
      "vocabulary reference drifted; run node tools/public/codegen/vocabulary.mjs --write\n",
    );
    process.exitCode = 1;
  } else
    process.stdout.write(
      "vocabulary reference and Debug API wording match shared source\n",
    );
} else {
  process.stderr.write(
    "Usage: node tools/public/codegen/vocabulary.mjs --write|--check\n",
  );
  process.exitCode = 2;
}
