"""Regenerate the static MCP catalog from the packaged Chrome Control helper's tools/list.

Uses only Python's standard library and the helper's owned pipe, with disposable state and no browser.
Maintainers run --helper PATH --write; --check verifies the generated Rust without writing it.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile
import threading

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "crates/vw-agent-tools/src/chrome_specs.rs"
NAMES = ("chrome_status", "chrome_session", "chrome_execute")
HEADER = """//! Static Chrome MCP definitions, advertised only when the core enables the catalog at session launch.
//! GENERATED by `tools/public/codegen/chrome_catalog.py` from the release helper; do not edit by hand.
//! Depends on `serde_json`; called by `mcp`. The real-helper drift test pins names, descriptions and schemas.

use serde_json::{Value, json};

pub(crate) fn tool_list() -> Vec<Value> {
    // Native discovery cannot render a root oneOf; the gateway validates action/args versus steps.
    vec![chrome_status(), chrome_session(), chrome_execute()]
}
"""


def catalog(helper):
    """Read the real helper's catalog while keeping its owner pipe open through both replies."""
    with tempfile.TemporaryDirectory(prefix="chrome-catalog-", dir=os.getenv("VW_TEST_ROOT")) as state:
        with subprocess.Popen([str(helper), "owned", "--state-dir", state],
                              stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                              text=True, encoding="utf-8") as child:
            timer = threading.Timer(30, child.kill)
            timer.start()
            try:
                def send(request):
                    child.stdin.write(json.dumps(request) + "\n")
                    child.stdin.flush()

                def reply(identity):
                    value = json.loads(child.stdout.readline())
                    if value.get("id") != identity or "result" not in value:
                        raise ValueError(f"unexpected helper reply: {value}")
                    return value["result"]

                send({"protocol": "vibework-owned/1", "secret": "01" * 32})
                send({"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
                    "protocolVersion": "2025-11-25", "capabilities": {},
                    "clientInfo": {"name": "catalog-generator", "version": "1"}}})
                reply(1)
                send({"jsonrpc": "2.0", "method": "notifications/initialized"})
                send({"jsonrpc": "2.0", "id": 2, "method": "tools/list", "params": {}})
                tools = reply(2)["tools"]
                child.stdin.close()
                if child.wait(timeout=10) != 0:
                    raise ValueError("helper did not exit successfully")
                return tools
            finally:
                timer.cancel()
                if child.poll() is None:
                    child.kill()


def render(tools):
    """Preserve every helper field except the root oneOf unsupported by native tool discovery."""
    if len(tools) != len(NAMES) or {tool["name"] for tool in tools} != set(NAMES):
        raise ValueError("unexpected Chrome tool names")
    by_name = {tool["name"]: tool for tool in tools}
    by_name["chrome_execute"]["inputSchema"].pop("oneOf", None)
    blocks = []
    for name in NAMES:
        lines = json.dumps(by_name[name], ensure_ascii=False, indent=4).splitlines()
        blocks.append(f"\nfn {name}() -> Value {{\n    json!(" + "\n    ".join(lines) + ")\n}\n")
    return HEADER + "".join(blocks)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--helper", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(catalog(args.helper.resolve(strict=True)))
    if args.write:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    elif OUTPUT.read_text(encoding="utf-8") != generated:
        raise SystemExit("Chrome catalog differs: regenerate with --helper PATH --write")
    print(f"Chrome catalog {'written' if args.write else 'matches helper'}: {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
